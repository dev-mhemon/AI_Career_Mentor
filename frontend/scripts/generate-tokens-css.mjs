// Generates src/styles/tokens.css from src/styles/design-tokens.json.
// Run: node scripts/generate-tokens-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const t = JSON.parse(readFileSync(new URL('src/styles/design-tokens.json', root), 'utf8'));

const px = (d) => (d.value === 0 ? '0' : `${d.value}${d.unit}`);

/** Resolve `{a.b.c}` refs to CSS values. */
function ref(v) {
  const m = /^\{(.+)\}$/.exec(v);
  if (!m) return v;
  const p = m[1].split('.');
  if (p[0] === 'color' && p[1] === 'primitive') return `var(--color-${p[2]}-${p[3]})`;
  if (p[0] === 'typography') {
    const [, group, key] = p;
    if (group === 'fontFamily') return `var(--font-${key})`;
    if (group === 'fontSize') return `var(--text-${key})`;
    if (group === 'fontWeight') return String(t.typography.fontWeight[key].$value);
    if (group === 'lineHeight') return String(t.typography.lineHeight[key].$value);
    if (group === 'letterSpacing') return px(t.typography.letterSpacing[key].$value);
  }
  throw new Error(`unresolved ref ${v}`);
}

function leaves(obj, path = []) {
  const out = [];
  for (const k of Object.keys(obj)) {
    if (k.startsWith('$')) continue;
    const v = obj[k];
    if (v.$value !== undefined) out.push([[...path, k].join('-'), v.$value]);
    else out.push(...leaves(v, [...path, k]));
  }
  return out;
}

const primitives = [];
for (const [ramp, steps] of Object.entries(t.color.primitive))
  for (const [step, tok] of Object.entries(steps))
    primitives.push(`  --color-${ramp}-${step}: ${tok.$value};`);

const semLight = leaves(t.theme.light);
const semDark = leaves(t.theme.dark);
const semDecl = (list) => list.map(([n, v]) => `  --${n}: ${ref(v)};`).join('\n');

const themeInline = semLight.map(([n]) => `  --color-${n}: var(--${n});`).join('\n');

const sizes = Object.entries(t.typography.fontSize).map(([k, v]) => `  --text-${k}: ${px(v.$value)};`);
const space = Object.entries(t.dimension.space).map(([k, v]) => `  --space-${k}: ${px(v.$value)};`);
const radius = Object.entries(t.dimension.radius).map(([k, v]) => `  --radius-${k}: ${px(v.$value)};`);
const sizing = Object.entries(t.dimension.sizing).map(([k, v]) => `  --size-${k}: ${px(v.$value)};`);
const shadows = Object.entries(t.shadow).map(([k, { $value: s }]) => {
  return `  --shadow-${k}: ${px(s.offsetX)} ${px(s.offsetY)} ${px(s.blur)} ${px(s.spread)} ${s.color};`;
});
const z = Object.entries(t.zIndex).map(([k, v]) => `  --z-${k}: ${v.$value};`);
const dur = Object.entries(t.motion.duration).map(([k, v]) => `  --duration-${k}: ${px(v.$value)};`);
const ease = Object.entries(t.motion.easing).map(([k, v]) => `  --ease-${k}: cubic-bezier(${v.$value.join(', ')});`);
const fonts = Object.entries(t.typography.fontFamily).map(([k, v]) => {
  const first = { 'Hind Siliguri': 'var(--font-hind-siliguri)', Inter: 'var(--font-inter)', 'JetBrains Mono': 'var(--font-jetbrains-mono)' };
  const stack = v.$value.map((f) => first[f] ?? (/\s/.test(f) ? `"${f}"` : f));
  return `  --font-${k}: ${stack.join(', ')};`;
});
const opacity = Object.entries(t.opacity).map(([k, v]) => `  --opacity-${k}: ${v.$value};`);

const textUtils = Object.entries(t.typography.textStyle).map(([name, { $value: s }]) =>
  `@utility text-${name} {\n  font-family: ${ref(s.fontFamily)};\n  font-size: ${ref(s.fontSize)};\n  font-weight: ${ref(s.fontWeight)};\n  line-height: ${ref(s.lineHeight)};\n  letter-spacing: ${ref(s.letterSpacing)};\n}`,
);

const css = `/* GENERATED by scripts/generate-tokens-css.mjs from design-tokens.json. Do not edit. */

@theme static {
${primitives.join('\n')}
${fonts.join('\n')}
${sizes.join('\n')}
${radius.join('\n')}
${shadows.join('\n')}
${ease.join('\n')}
}

@theme inline {
${themeInline}
}

:root {
${space.join('\n')}
${sizing.join('\n')}
${z.join('\n')}
${dur.join('\n')}
${opacity.join('\n')}
  --focus-ring-width: ${px(t.focusRing.width.$value)};
  --focus-ring-offset-width: ${px(t.focusRing.offset.$value)};
}

:root,
[data-theme='light'] {
  color-scheme: light;
${semDecl(semLight)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${semDecl(semDark).replace(/^/gm, '  ')}
  }
}

[data-theme='dark'] {
  color-scheme: dark;
${semDecl(semDark)}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0ms;
    --duration-normal: 0ms;
    --duration-slow: 0ms;
  }
  *,
  *::before,
  *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
    scroll-behavior: auto !important;
  }
}

${textUtils.join('\n\n')}
`;

writeFileSync(new URL('src/styles/tokens.css', root), css);
console.log(`semantic light=${semLight.length} dark=${semDark.length} primitives=${primitives.length}`);
